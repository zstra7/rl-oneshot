#!/usr/bin/env node
/**
 * N0 (plan/ONLINE_MULTIPLAYER_PLAN.md): the app depends on the
 * cross-platform-deterministic Rapier build, installed via an npm alias
 * in package.json:
 *
 *   "@dimforge/rapier3d-compat": "npm:@dimforge/rapier3d-deterministic-compat@0.19.3"
 *
 * That build's RUNTIME is correct and fully passes the physics suite,
 * but its TypeScript declarations have an upstream packaging bug:
 * `raw.d.ts` re-exports from `./rapier_wasm3d-deterministic`, a file the
 * tarball never ships (it ships `rapier_wasm3d.d.ts`, without the
 * `-deterministic` suffix). So `vue-tsc --noEmit` fails with dozens of
 * "Module '../raw' has no exported member 'Raw…'" errors even though the
 * runtime is fine.
 *
 * This postinstall shim is purely ADDITIVE: it creates the file the
 * package's own `raw.d.ts` asks for (`rapier_wasm3d-deterministic.d.ts`)
 * as a one-line re-export of the file that actually ships. It never edits
 * a vendored file, is idempotent, and no-ops cleanly if upstream ever
 * fixes the packaging (or the standard, non-deterministic build is in
 * place, whose `raw.d.ts` points elsewhere). Keeping this out of a broad
 * `skipLibCheck: true` preserves strict declaration checking for every
 * other dependency.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "node_modules",
  "@dimforge",
  "rapier3d-compat"
);

const rawDts = join(pkgDir, "raw.d.ts");
const shimTarget = join(pkgDir, "rapier_wasm3d-deterministic.d.ts");
const realWasmDts = join(pkgDir, "rapier_wasm3d.d.ts");

// Only act when: the package is present, its raw.d.ts references the
// missing `-deterministic` module, the shipped `rapier_wasm3d.d.ts`
// exists, and we haven't already written the shim.
if (!existsSync(rawDts) || !existsSync(realWasmDts)) {
  process.exit(0);
}

const rawReferencesDeterministic = readFileSync(rawDts, "utf8").includes("rapier_wasm3d-deterministic");
if (!rawReferencesDeterministic || existsSync(shimTarget)) {
  process.exit(0);
}

writeFileSync(
  shimTarget,
  "// Auto-generated by scripts/patch-rapier-deterministic-types.mjs — see that file.\n" +
    "// Supplies the declaration module @dimforge/rapier3d-deterministic-compat's\n" +
    "// raw.d.ts re-exports but forgot to ship.\n" +
    'export * from "./rapier_wasm3d";\n'
);

process.stdout.write("[patch-rapier] wrote rapier_wasm3d-deterministic.d.ts type shim\n");
