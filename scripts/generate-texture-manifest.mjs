// Scans public/assets/textures/ and (re)generates:
//   - src/assets/textures/TextureManifestData.ts (the committed manifest)
//   - docs/texture-intake-report.md (asset pipeline spec section 25)
//
// Run with: node scripts/generate-texture-manifest.mjs
//
// All 298 supplied files are small (32x64/64x64) tiling PSX-style surface
// textures with no separate normal/roughness/metalness/AO maps (checked by
// hand against the filename list before writing this script — see
// docs/asset-pipeline-deviations.md Phase 12) so every entry is classified
// `semantic: "color"`. That classification is an authorial decision (spec
// section 22: "Do not discover texture semantics solely from filename...
// manifest is authoritative"), not something this script infers on its
// own each run — if a future supplied texture needs a different semantic,
// add it to `SEMANTIC_OVERRIDES` below rather than relying on the default.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const rootDir = fileURLToPath(new URL("..", import.meta.url));
const texturesDir = `${rootDir}/public/assets/textures`;

/** id (filename without extension) -> semantic override. Empty: none needed yet. */
const SEMANTIC_OVERRIDES = {};

function readPngHeader(filePath) {
  const buffer = readFileSync(filePath);
  if (buffer.length < 33 || buffer.readUInt32BE(0) !== 0x89504e47) {
    throw new Error(`${filePath}: not a valid PNG (bad signature)`);
  }
  const width = buffer.readUInt32BE(16);
  const height = buffer.readUInt32BE(20);
  const bitDepth = buffer.readUInt8(24);
  const colorType = buffer.readUInt8(25);
  // 3 = palette (may carry alpha via a tRNS chunk, common in this pack),
  // 4/6 = grayscale+alpha / RGBA (always alpha).
  const hasAlpha = colorType === 4 || colorType === 6 || (colorType === 3 && bufferHasTrns(buffer));
  return { width, height, bitDepth, colorType, hasAlpha };
}

function bufferHasTrns(buffer) {
  let offset = 8;
  while (offset + 8 <= buffer.length) {
    const length = buffer.readUInt32BE(offset);
    const type = buffer.toString("ascii", offset + 4, offset + 8);
    if (type === "tRNS") {
      return true;
    }
    if (type === "IDAT" || type === "IEND") {
      return false;
    }
    offset += 8 + length + 4;
  }
  return false;
}

function isPowerOfTwo(n) {
  return n > 0 && (n & (n - 1)) === 0;
}

const files = readdirSync(texturesDir)
  .filter((name) => name.toLowerCase().endsWith(".png"))
  .sort();

const entries = [];
const reportRows = [];

for (const file of files) {
  const id = file.replace(/\.png$/i, "");
  const filePath = `${texturesDir}/${file}`;
  const { width, height, hasAlpha } = readPngHeader(filePath);
  const semantic = SEMANTIC_OVERRIDES[id] ?? "color";
  const warnings = [];

  if (!isPowerOfTwo(width) || !isPowerOfTwo(height)) {
    // A handful of this pack's tiles are legitimately non-square/non-POT
    // (e.g. 32x64 half-tiles designed to sit next to a 64x64 tile) — still
    // flagged per spec section 25/26.2 so it is visible in the report,
    // not treated as an error (mipmapping still works on non-POT in
    // WebGL2/three r160, just without the guaranteed tiling seam quality).
    warnings.push("non-power-of-two dimension");
  }
  if (width > 2048 || height > 2048) {
    warnings.push("exceeds 2048px hard warning threshold");
  }

  entries.push({
    id,
    file,
    width,
    height,
    hasAlpha,
    semantic,
    warnings
  });

  reportRows.push(
    `| \`${file}\` | ${width}x${height} | PNG | ${semantic} | optional | ${
      semantic === "color" ? "sRGB" : "linear"
    } | pixel-mipmapped | repeat | ${hasAlpha ? "yes" : "no"} | ${warnings.join("; ") || "-"} |`
  );
}

const manifestTs = `// GENERATED by scripts/generate-texture-manifest.mjs — do not hand-edit.
// Regenerate with: node scripts/generate-texture-manifest.mjs
import type { TextureAssetDescriptor } from "@/assets/textures/TextureTypes";

export const TEXTURE_MANIFEST_ENTRIES: readonly TextureAssetDescriptor[] = [
${entries
  .map(
    (e) => `  {
    id: ${JSON.stringify(e.id)},
    url: ${JSON.stringify(`/assets/textures/${e.file}`)},
    semantic: ${JSON.stringify(e.semantic)},
    required: false,
    filtering: "pixel-mipmapped",
    wrapS: "repeat",
    wrapT: "repeat",
    repeat: { x: 1, y: 1 },
    flipY: true
  }`
  )
  .join(",\n")}
];
`;

writeFileSync(`${rootDir}/src/assets/textures/TextureManifestData.ts`, manifestTs);

const alphaCount = entries.filter((e) => e.hasAlpha).length;
const warnCount = entries.filter((e) => e.warnings.length > 0).length;

const reportMd = `# Texture Intake Report

Generated by \`scripts/generate-texture-manifest.mjs\` from
\`public/assets/textures/\` (asset pipeline spec section 25). ${entries.length}
files scanned, ${alphaCount} with an alpha channel, ${warnCount} with a
warning. None are individually \`required\` yet — see
\`docs/asset-pipeline-deviations.md\` Phase 12 for why.

Excluded (not in-game textures — vendor catalog/preview images, left in
place at \`assets/textures/\`, not moved to \`public/\` or added to the
manifest): \`Listing_image.png\` (1260x1000), \`Render.png\` (1920x1080),
\`Thumbnail.png\` (256x256).

## Files

| File | Dimensions | Format | Semantic | Required | Colour space | Filtering | Wrapping | Alpha | Warnings |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${reportRows.join("\n")}
`;

writeFileSync(`${rootDir}/docs/texture-intake-report.md`, reportMd);

console.log(`Generated manifest for ${entries.length} textures (${warnCount} with warnings).`);
